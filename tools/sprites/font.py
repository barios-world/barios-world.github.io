def text_width(s, gap=1):
    w = 0
    for ch in s.upper():
        g = F.get(ch, F['?'])
        w += len(g.split('|')[0]) + gap
    return w - gap if s else 0


def draw_text(grid, x, y, s, c, gap=1, shadow=None):
    """Draw uppercase text; 'h' = heart, '>' = arrow. Returns end x."""
    cx = x
    for ch in s.upper():
        glyph = F.get(ch, F['?'])
        rows = glyph.split('|')
        w = len(rows[0])
        for j, row in enumerate(rows):
            for i, bit in enumerate(row):
                if bit == '#':
                    if shadow:
                        grid.set(cx + i + 1, y + j + 1, shadow)
                    grid.set(cx + i, y + j, c)
        cx += w + gap
    return cx
